/**
 * `FileFunctionLibraryStore` — the default `FunctionLibraryStore` (03-data-model.md
 * §11, 05-registry.md §4), backed by the workspace `lib/` directory.
 *
 * One function per file, named by kebab-casing the function name; `lib/index.ts`
 * re-exports them all. The file is the only storage — there is no sidecar index,
 * no database, and `code` is the file content verbatim. Node-only, which is why
 * it lives here and not in core.
 */

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  CodeFlowError,
  validateFunctionInputSchema,
  validateFunctionName,
  validateModulePath,
  type FunctionDefinition,
  type FunctionLibraryStore,
  type RemoveFunctionOptions,
  type SaveFunctionOptions,
} from "@codeflow/core";
import {
  DEFAULT_MODULE_PATH,
  kebabCase,
  parseFunctionFile,
  renameInSource,
  serializeFunctionFile,
  stripFunctionHeader,
} from "./metadata.js";

export interface FileFunctionLibraryStoreOptions {
  /** Absolute path of the library directory (the workspace `lib/`). */
  dir: string;
  /** `modulePath` given to functions whose file omits it. Default `"@flows/lib"`. */
  modulePath?: string;
  /**
   * Usage check (03 §11): removing a function that flows still call must be
   * refused unless the user confirmed. The store cannot know usage on its own —
   * the host (`codeflow check`, or a scan of the open flows) supplies it.
   */
  isInUse?: (name: string) => boolean | Promise<boolean>;
}

interface Entry {
  def: FunctionDefinition;
  file: string;
}

const INDEX_FILE = "index.ts";

const INDEX_HEADER = [
  "// Generated by CodeFlow — re-exports every function in this library.",
  "// The function files in this directory are the storage; this index is derived",
  "// from them and is rewritten by `codeflow generate` and by the library store.",
].join("\n");

async function readDirectory(dir: string): Promise<string[]> {
  try {
    return await readdir(dir);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  }
}

export class FileFunctionLibraryStore implements FunctionLibraryStore {
  readonly dir: string;
  private readonly modulePath: string;
  private readonly isInUse: ((name: string) => boolean | Promise<boolean>) | undefined;

  constructor(options: FileFunctionLibraryStoreOptions) {
    this.dir = path.resolve(options.dir);
    this.modulePath = options.modulePath ?? DEFAULT_MODULE_PATH;
    this.isInUse = options.isInUse;
  }

  /** Path a function's file gets — derived from the name, never stored. */
  fileFor(name: string): string {
    return path.join(this.dir, `${kebabCase(name)}.ts`);
  }

  async list(): Promise<FunctionDefinition[]> {
    return (await this.entries()).map((entry) => entry.def);
  }

  async get(name: string): Promise<FunctionDefinition | null> {
    const entry = await this.find(name);
    return entry === null ? null : entry.def;
  }

  async save(def: FunctionDefinition, opts: SaveFunctionOptions = {}): Promise<void> {
    this.validate(def);
    const existing = await this.find(def.name);
    if (existing !== null && opts.overwrite !== true) {
      throw new CodeFlowError(
        "duplicate-function",
        `Function "${def.name}" already exists in the library — save with { overwrite: true } to replace it.`,
      );
    }

    const target = this.fileFor(def.name);
    const occupant = (await this.entries()).find(
      (entry) => entry.file === target && entry.def.name !== def.name,
    );
    if (occupant !== undefined) {
      throw new CodeFlowError(
        "duplicate-function",
        `Function "${def.name}" would be stored at ${path.basename(target)}, which already holds "${occupant.def.name}".`,
      );
    }

    await mkdir(this.dir, { recursive: true });
    await writeFile(target, serializeFunctionFile({ ...def, modulePath: def.modulePath || this.modulePath }), "utf8");
    // A rename done through save() (same name, different derived file) leaves the
    // old file behind — drop it so the directory keeps one file per function.
    if (existing !== null && existing.file !== target) await rm(existing.file, { force: true });
    await this.writeIndex();
  }

  async remove(name: string, opts: RemoveFunctionOptions = {}): Promise<void> {
    const entry = await this.find(name);
    if (entry === null) {
      throw new CodeFlowError("function-not-found", `Function "${name}" is not in the library.`);
    }
    if (opts.force !== true && this.isInUse !== undefined && (await this.isInUse(name))) {
      throw new CodeFlowError(
        "function-in-use",
        `Function "${name}" is still used by at least one flow — resolve the usages or remove with { force: true }.`,
      );
    }
    await rm(entry.file, { force: true });
    await this.writeIndex();
  }

  /**
   * Renames the function: its file, its metadata and the binding inside its own
   * source. Flows importing the old name are NOT rewritten — that is a patch per
   * flow (`codeflow check` lists them; the host/user decides) — 03 §11.
   */
  async rename(oldName: string, newName: string): Promise<void> {
    const entry = await this.find(oldName);
    if (entry === null) {
      throw new CodeFlowError("function-not-found", `Function "${oldName}" is not in the library.`);
    }
    validateFunctionName(newName);
    if (oldName === newName) return;
    if ((await this.find(newName)) !== null) {
      throw new CodeFlowError(
        "duplicate-function",
        `Cannot rename "${oldName}" to "${newName}": that name already exists in the library.`,
      );
    }

    const source = renameInSource(stripFunctionHeader(entry.def.code), oldName, newName);
    const target = this.fileFor(newName);
    await mkdir(this.dir, { recursive: true });
    await writeFile(
      target,
      serializeFunctionFile({ ...entry.def, name: newName, code: source }),
      "utf8",
    );
    if (target !== entry.file) await rm(entry.file, { force: true });
    await this.writeIndex();
  }

  /** Rewrites `lib/index.ts` so it re-exports exactly the functions on disk. */
  async writeIndex(): Promise<void> {
    const entries = await this.entries();
    const exports = entries
      .map((entry) => `export * from "./${path.basename(entry.file, ".ts")}.js";`)
      .sort();
    const body = exports.length === 0 ? ["export {};"] : exports;
    await mkdir(this.dir, { recursive: true });
    await writeFile(path.join(this.dir, INDEX_FILE), `${INDEX_HEADER}\n\n${body.join("\n")}\n`, "utf8");
  }

  private async entries(): Promise<Entry[]> {
    const names = await readDirectory(this.dir);
    const entries: Entry[] = [];
    for (const name of names.sort()) {
      if (!name.endsWith(".ts") || name.endsWith(".d.ts") || name === INDEX_FILE) continue;
      const file = path.join(this.dir, name);
      const content = await readFile(file, "utf8");
      const def = parseFunctionFile(name, content, { modulePath: this.modulePath });
      if (def !== null) entries.push({ def, file });
    }
    return entries.sort((a, b) => (a.def.name < b.def.name ? -1 : a.def.name > b.def.name ? 1 : 0));
  }

  private async find(name: string): Promise<Entry | null> {
    return (await this.entries()).find((entry) => entry.def.name === name) ?? null;
  }

  private validate(def: FunctionDefinition): void {
    validateFunctionName(def.name);
    validateFunctionInputSchema(def.name, def.inputSchema);
    validateModulePath(def.modulePath || this.modulePath);
  }
}
